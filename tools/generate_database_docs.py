"""Write ``docs/DATABASE.md`` from the real schema and the real method docstrings.

    python tools/generate_database_docs.py

The tables and the method lists come from a fresh temporary database and from
``database/repositories.py``, so the document cannot drift away from the code.
"""

import inspect
import os
import sys
import tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)

from database.db_manager import DatabaseManager  # noqa: E402
from database.repositories import REPOSITORIES  # noqa: E402

TABLE_NOTES = {
    "users": "Accounts. `role` is `manager` or `employee`; `status` is `approved`, `pending` or `rejected`.",
    "sessions": "One work session of one employee: the three time counters and the screen counters.",
    "events": "Focus / distraction / away transitions logged during a session.",
    "tasks": "To-do items. `assigned_by` is NULL for personal tasks; deadline columns are optional.",
    "calendar_events": "Calendar entries created by a manager.",
    "calendar_attendees": "Which employees are invited to an event.",
    "ai_chats": "AI Chat conversations (one owner each).",
    "ai_messages": "Messages of a chat. `source` says who wrote an assistant message: `engine` or `llm`.",
    "knowledge_docs": "The manager's documents for the assistant. `visibility` is `everyone` or `managers`.",
}

MIGRATIONS = [
    ("users.status", "added when sign-up approval was introduced", "`ALTER TABLE users ADD COLUMN status TEXT NOT NULL DEFAULT 'approved'` (old accounts stay approved)"),
    ("sessions.screen_*_seconds", "added with screen monitoring", "three `INTEGER DEFAULT 0` columns"),
    ("sessions.distraction_seconds", "distraction became a time counter, not a count", "column added; old rows keep 0"),
    ("tasks.description", "task descriptions", "`TEXT DEFAULT NULL`"),
    ("tasks.deadline_date / deadline_time", "deadlines", "two nullable `TEXT` columns (`YYYY-MM-DD`, `HH:MM`)"),
    ("calendar_events / calendar_attendees", "calendar", "`CREATE TABLE IF NOT EXISTS`"),
    ("ai_chats / ai_messages", "AI Chat", "`CREATE TABLE IF NOT EXISTS` + indexes"),
    ("ai_messages.source", "who wrote a reply (privacy of the model's memory)", "nullable `TEXT`; NULL on older rows"),
    ("knowledge_docs", "documents for the assistant", "`CREATE TABLE IF NOT EXISTS`"),
]


def first_line(function):
    doc = inspect.getdoc(function) or ""
    return doc.splitlines()[0] if doc else ""


def signature_of(function):
    text = str(inspect.signature(function)).replace("(self, ", "(").replace("(self)", "()")
    return text


def main():
    folder = tempfile.mkdtemp()
    db = DatabaseManager(os.path.join(folder, "doc.db"))
    out = []
    out.append("# Database\n")
    out.append("*Generated by `python tools/generate_database_docs.py` from the real schema -- do not edit by hand.*\n")
    out.append("""SQLite, one file: `data/office_assistant.db`, opened by `database.db_manager.DatabaseManager`.
The connection is created with `check_same_thread=False`, **but it is only used from the Qt main thread**
(see [THREADING.md](THREADING.md)). Foreign keys are switched on (`PRAGMA foreign_keys = ON`).
""")
    out.append("## Tables\n")
    for row in db.conn.execute("SELECT name, sql FROM sqlite_master WHERE type='table' AND name NOT LIKE 'sqlite_%' ORDER BY name"):
        out.append("### `%s`\n" % row["name"])
        out.append(TABLE_NOTES.get(row["name"], "") + "\n")
        out.append("| column | type | notes |\n|---|---|---|")
        for col in db.conn.execute("PRAGMA table_info(%s)" % row["name"]):
            notes = []
            if col["pk"]:
                notes.append("primary key")
            if col["notnull"] and not col["pk"]:
                notes.append("not null")
            if col["dflt_value"] is not None:
                notes.append("default %s" % col["dflt_value"])
            out.append("| %s | %s | %s |" % (col["name"], col["type"] or "", ", ".join(notes)))
        for fk in db.conn.execute("PRAGMA foreign_key_list(%s)" % row["name"]):
            out.append("| *FK* %s | -> %s.%s | on delete %s |" % (fk["from"], fk["table"], fk["to"], fk["on_delete"].lower()))
        out.append("")
    out.append("Indexes: " + ", ".join("`%s`" % r["name"] for r in db.conn.execute(
        "SELECT name FROM sqlite_master WHERE type='index' AND name NOT LIKE 'sqlite_%' ORDER BY name")) + ".\n")

    out.append("## Migrations\n")
    out.append("""`create_tables()` runs `CREATE TABLE IF NOT EXISTS` for every table, then checks each table with
`PRAGMA table_info` and adds a missing column with `ALTER TABLE ... ADD COLUMN`. It never drops or rewrites data, so
an older database file opens, is upgraded in place, and keeps all its rows (`tests/test_db_core.py` builds an old-format
database and checks exactly that).
""")
    out.append("| change | why | how |\n|---|---|---|")
    for name, why, how in MIGRATIONS:
        out.append("| %s | %s | %s |" % (name, why, how))
    out.append("")

    out.append("## Access: repositories\n")
    out.append("""`DatabaseManager` keeps its full, backward-compatible API (`db.get_user(...)`). On top of it, every
public method belongs to exactly one *repository* -- a narrow view with the same shared connection
(`database/repositories.py`). New code depends on the smallest one it needs:

```python
chats = db.chats          # only the chat methods
chats.add_ai_message(...)  # fine
chats.delete_user_cascade  # AttributeError: it belongs to another repository
```

`tests/test_repositories.py` fails if a new method is added to `DatabaseManager` without being listed in a repository.
""")
    manager_functions = dict(inspect.getmembers(DatabaseManager, inspect.isfunction))
    for attribute, repository in REPOSITORIES.items():
        out.append("### `db.%s` -- %s\n" % (attribute, (repository.__doc__ or "").strip()))
        out.append("| method | what it does |\n|---|---|")
        for name in repository.METHODS:
            function = manager_functions[name]
            out.append("| `%s%s` | %s |" % (name, signature_of(function).replace("|", "\\|"), first_line(function).replace("|", "\\|")))
        out.append("")
    out.append("Infrastructure (not part of a repository): `create_tables`, `seed_demo_users`, `close`.\n")

    out.append("## Rules the code follows\n")
    out.append("""* Every write is committed in the method that makes it; multi-table operations (`delete_user_cascade`,
  `factory_reset`) run in one transaction.
* Only the database layer writes SQL. The UI and the assistant call named methods (the last direct `db.conn` uses in
  the admin panel were moved into `create_user`, `username_taken`, `count_user_related_rows`, `delete_all_tasks`).
* Dates are `YYYY-MM-DD`, times `HH:MM` or `HH:MM:SS`, timestamps `YYYY-MM-DD HH:MM:SS` in local time.
* Passwords are stored **as typed** (see the limitation in [PRIVACY.md](PRIVACY.md)).
""")
    db.close()
    path = os.path.join(ROOT, "docs", "DATABASE.md")
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as handle:
        handle.write("\n".join(out))
    print("wrote", path)


if __name__ == "__main__":
    main()
